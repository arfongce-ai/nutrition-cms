function buildProduct([productName, calories, saturatedFat, sugar, protein, sodium, allergens, servingGram, extraNote], categoryLabel) {
  const gram = servingGram || 100;
  const isEstimatedGram = !servingGram;
  const servingSize = isEstimatedGram ? '100g 기준(추정 — 표에 "100g당" 직접 명시 안 됨)' : `1개(${gram}g) 기준`;

  const noteParts = [
    '자담치킨 공식 홈페이지 "제품 영양정보" 표(이미지)를 Claude가 화면 캡처로 옮겨 적었습니다(AI가 이미지에서 읽음 — 원본 대조 필요).',
    isEstimatedGram
      ? '표에 "100g당"이라는 문구가 직접 적혀있지 않아, 2026년 보도자료(요기요 100g당 열량 표시)와 수치 규모를 근거로 100g 기준으로 추정해 저장했습니다. 1인분(전체 수량) 기준이 아닙니다.'
      : '표에 중량이 직접 적혀 있어 그 중량 기준 확정값입니다.',
  ];
  if (extraNote) noteParts.push(extraNote);

  return {
    id: `jadam-${stableId(`${categoryLabel}|${productName}`)}`,
    brand,
    productName,
    aliases: [...new Set([`자담치킨 ${productName}`, `자담 ${productName}`, productName, productName.replace(/\s+/g, '')])],
    category: `${brand}/${categoryLabel}`,
    servingSize,
    servingGram: gram,
    sourceType: 'ai_image_transcription',
    sourceLabel,
    sourceUrl,
    verifiedAt,
    allergens: allergens || [],
    additiveWatch: [saturatedFat >= 10 ? '포화지방' : ''].filter(Boolean),
    nutrients: {
      calories,
      carb: null,
      sugar,
      protein,
      fat: null,
      saturatedFat,
      transFat: null,
      sodium,
      caffeine: null,
    },
    reviewNote: noteParts.join(' '),
  };
}

